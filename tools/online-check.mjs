import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
const server = spawn(process.execPath, ['tools/serve.mjs'], { env: { ...process.env, PORT: '4187', HOST: '127.0.0.1' }, stdio: 'inherit' });
const base = 'http://127.0.0.1:4187';
let browser;
const api = async (route, data, session, method = 'POST') => {
  const response = await fetch(base + '/api/' + route, { method, headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + (session?.token || '') }, body: method === 'POST' ? JSON.stringify({ code: session?.code, ...data }) : undefined });
  return { status: response.status, data: await response.json() };
};
try {
  for (let i = 0; i < 100; i++) { try { await fetch(base); break; } catch { await new Promise(r => setTimeout(r, 100)); } }
  const host = (await api('create', {})).data;
  assert.equal((await api('action', { action: 'start' }, host)).status, 409);
  const guest = (await api('join', { code: host.code })).data;
  assert.equal((await api('join', { code: host.code })).status, 409);
  assert.equal((await api('action', { action: 'start' }, guest)).status, 409);
  assert.equal((await api('action', { action: 'start' }, host)).status, 200);
  assert.equal((await api('action', { action: 'plant', type: 1, row: 2, col: 2 }, guest)).status, 409);
  assert.equal((await api('action', { action: 'plant', type: 1, row: 2, col: 2 }, host)).status, 200);
  assert.equal((await api('action', { action: 'spawn', type: 0, row: 2 }, guest)).status, 200);
  assert.equal((await api('action', { action: 'spawn', type: -1, row: 2 }, guest)).status, 409);
  assert.equal((await api('action', { action: 'pause' }, host)).status, 200);
  const state = async s => (await api('state?code=' + s.code, undefined, s, 'GET')).data;
  const a = await state(host), b = await state(guest);
  assert.equal(a.battle.time, b.battle.time);
  assert.deepEqual(a.battle.plants, b.battle.plants);
  assert.deepEqual(a.battle.zombies, b.battle.zombies);
  assert.equal(a.battle.paused, true);
  await api('action', { action: 'pause' }, host);
  await new Promise(r => setTimeout(r, 5300));
  const stopped = await state(host);
  assert.equal(stopped.connected, false);
  await new Promise(r => setTimeout(r, 250));
  assert.equal((await state(host)).battle.time, stopped.battle.time);
  await state(guest);
  await new Promise(r => setTimeout(r, 150));
  assert.ok((await state(host)).battle.time > stopped.battle.time);
  await api('leave', {}, host);
  assert.equal((await api('state?code=' + guest.code, undefined, guest, 'GET')).status, 404);
  console.log('PASS API: room capacity, host start, role enforcement, invalid input, synchronized state, pause, disconnect/reconnect, leave');
  browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
  const p1 = await browser.newPage(), p2 = await browser.newPage();
  const errors = [];
  for (const p of [p1, p2]) p.on('pageerror', e => errors.push(e.message));
  await Promise.all([p1.goto(base), p2.goto(base)]);
  await p1.locator('#create-room').click();
  await p1.waitForFunction(() => window.duel?.online.session);
  const code = await p1.evaluate(() => window.duel.online.session.code);
  await p2.locator('#room-code').fill(code);
  await p2.locator('#join-room').click();
  await p1.waitForFunction(() => window.duel.online.connected);
  await p1.locator('#start-room').click();
  await Promise.all([p1.waitForFunction(() => window.duel.started), p2.waitForFunction(() => window.duel.started)]);
  await p1.locator('#online summary').click();
  await p2.locator('#online summary').click();
  await p1.locator('canvas').click({ position: { x: 30, y: 150 } });
  await p1.keyboard.press('Enter');
  await p2.locator('canvas').click({ position: { x: 30, y: 150 } });
  await p2.keyboard.press('e');
  for (const p of [p1, p2]) await p.waitForFunction(() => window.duel.battle.plants.length === 1 && window.duel.battle.zombies.length === 1);
  await p2.reload();
  await p2.waitForFunction(() => window.duel?.started && window.duel.online.session.role === 'zombies');
  await p1.screenshot({ path: 'reports/online-host.png' });
  await p2.screenshot({ path: 'reports/online-guest.png' });
  assert.deepEqual(errors, []);
  console.log('PASS browsers: create, join, start, keyboard actions sync, reload restores seat, no page errors');
} finally { await browser?.close(); server.kill(); }
